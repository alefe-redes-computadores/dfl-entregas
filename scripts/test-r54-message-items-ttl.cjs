#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const ts=require('typescript');
const crypto=require('node:crypto');
const file=s=>fs.readFileSync(s,'utf8');
const parse=p=>{const src=file(p);const tree=ts.createSourceFile(p,src,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);assert.equal(tree.parseDiagnostics.length,0,`TS parse: ${p}`);return ts.transpileModule(src,{fileName:p,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true},reportDiagnostics:true}).outputText};
function load(js,deps){const result={};vm.runInNewContext(js,{exports:result,require:p=>{if(!(p in deps))throw Error('Dependency not authorized: '+p);return deps[p]},Date,Number,Math,Set,Map,RegExp,console,URL,AbortController,fetch:globalThis.fetch,setTimeout,clearTimeout,process},{timeout:4000});return result;}
const policy=load(parse('lib/integration/manualMessagingPolicy.ts'),{});
const pickup=load(parse('lib/integration/manualPickupPolicy.ts'),{'./manualMessagingPolicy':policy});
const plan=policy.planManualMessage;
const now=Date.now();const created=new Date(now-2000).toISOString();
const base={id:'dfl-12345678-1234-1234-1234-123456789abc',origin:'loja',phone:'34999999999',customer_name:'Cliente consentido',fulfillment_mode:'delivery',notify_whatsapp:true,manual_messaging_opt_in_v1:true,created_at:created,manual_order_items:'2 Armaria e 1 Fanta 1 L',customer_charge:42.5};
const planned=plan({delivery:base,reason:'created',now});assert.equal(planned.eligible,true,'pedido real consentido elegivel');
const formatted=pickup.manualPickupItems(base.manual_order_items);
assert.equal(JSON.stringify(formatted),JSON.stringify([{name:'Armaria',quantity:2},{name:'Fanta 1 L',quantity:1}]));
assert.equal(pickup.manualPickupItems('').length,0,'vazio nao inventa produtos');
assert.equal(plan({delivery:{...base,manual_messaging_opt_in_v1:false},reason:'created',now}).eligible,false,'consentimento obrigatorio');
assert.equal(plan({delivery:{...base,developer_test:true},reason:'created',now}).eligible,false,'DEV continua bloqueado');
assert.equal(plan({delivery:{...base,origin:'ifood'},reason:'created',now}).eligible,false,'marketplace bloqueado');
const server=file('lib/integration/server/manualMessaging.ts');
assert.ok(server.includes("import { manualPickupItems } from '../manualPickupPolicy';"),'parser unico reutilizado');
assert.ok(server.includes("reason === 'created' ? manualPickupItems(delivery.manual_order_items) : []"),'itens so no evento created');
assert.ok(server.includes('...(items.length?{items}:{})'),'itens no envelope para worker');
assert.ok(server.includes('manual_messaging_opt_in_v1:true'),'optin preservado');
assert.ok(server.includes('event_id: `manual-msg-v1__${plan.eventType}__${delivery.id}`'),'identidade de evento imutavel');
assert.ok(server.includes('14000'),'ponte rapida preservada');
const client=file('app/mais/acompanhamento/page.tsx');
assert.ok(client.includes('requested_ttl_minutes:90,'),'API solicita 90min');
assert.ok(client.includes('Emitir link privado (90 min)'),'cta exibe 90min');
assert.ok(client.includes('válido por até 90 minutos'),'confirmacao explica o novo prazo');
assert.ok(!client.includes('requested_ttl_minutes:45,'),'nenhum ttl manual legado');
assert.ok(file('scripts/test-r265-link-handoff.cjs').includes('requested_ttl_minutes:90'),'regressao R265 atualizada');
const http=file('lib/tracking/gate1/http.ts');
assert.ok(http.includes('Number(v.requested_ttl_minutes) > 1440'),'backend suporta 90min sem nova alteracao');
const storage=file('lib/tracking/gate1/storage.ts');
assert.ok(storage.includes('input.ttlMinutes * 60_000'),'backend persiste TTL solicitado');
assert.ok(storage.includes('Math.min(now + 30 * 60_000,'),'sessao nao foi expandida');
console.log('R54: itens estruturados, descricao opcional, consentimento, DEV, marketplaces, dedupe, link 90min e sessao 30min OK');
