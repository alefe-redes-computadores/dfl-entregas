'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm'),ts=require('typescript');
const read=p=>fs.readFileSync(p,'utf8');
let checks=0; const ok=(condition,message)=>{assert.ok(condition,`R300 P3 BEBIDAS: ${message}`);checks++};
const load=(file,mocks={})=>{
 const module={exports:{}};
 const code=ts.transpileModule(read(file),{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 vm.runInNewContext(code,{module,exports:module.exports,require:dep=>{if(dep in mocks)return mocks[dep];throw Error('Import inesperado: '+dep)},Map,Number,String,Array,Set,Intl}, {filename:file,timeout:1800});
 return module.exports;
};
const parser=load('lib/operation/beverage-normalization.ts');
const agg=load('lib/operation/route-beverage-checklist.ts',{'@/lib/operation/beverage-normalization':parser});
const source=[{id:'a',name:'Cliente A',drinks:'COCA 1L'},{id:'b',name:'Cliente B',drinks:'1x COCA 1L'},{id:'c',name:'Cliente C',drinks:'COCA ZERO 2L'},{id:'d',name:'Cliente D',drinks:''}];
const result=agg.aggregateRouteBeverages(source);
ok(result.items.length===2,'COCA 1L e COCA ZERO 2L continuam diferentes');
const coca=result.items.find(x=>x.name==='COCA 1L');
ok(coca&&coca.qty===2&&coca.orders.length===2,'COCA 1L + 1x COCA 1L agregam como duas unidades');
ok(coca.orders[0].id==='a'&&coca.orders[1].id==='b','cada pedido conserva seu rastro');
ok(result.totalUnits===3&&result.orderCount===3,'quantidade e pedidos são contagens diferentes');
ok(result.unknown.length===0,'não inventa bebida desconhecida');
const review=agg.aggregateRouteBeverages([{id:'u1',name:'Cliente U',drinks:'TEXTO NAO RECONHECIDO'}]);
ok(review.items.length===0&&review.unknown.length===1&&review.totalUnits===0,'ambiguidade exige conferência, sem quantidade inventada');
const empty=agg.aggregateRouteBeverages([]);
ok(empty.totalUnits===0&&empty.orderCount===0,'rota vazia é segura');
const route=read('components/routes/RouteDepartureChecklist.tsx');
ok(route.includes('aggregateRouteBeverages(')&&route.includes('data-dfl-beverage-totals')&&route.includes('data-dfl-beverage-customer-review'),'checklist une resumo e detalhe por cliente');
ok(route.includes('Bebidas para pegar')&&route.includes('routeCashFlow(')&&route.includes('departureStopSummary('),'troco e paradas existentes preservados');
const whatsapp=read('lib/whatsapp.ts');
ok(whatsapp.includes('canonicalizeRouteDrinkName(')&&whatsapp.includes('drinksSummary[key].qty+=qty')&&!whatsapp.includes("import { parseBeverageTokens }"),'WhatsApp agrega bebidas sem import não suportado pela suíte legada R85');
ok(whatsapp.includes('deliveryStopKey')&&whatsapp.includes('ifoodPortalLines'),'identidade de parada e código iFood preservados');
const pre=read('scripts/pre-apk.cjs');
ok(pre.includes("'scripts/test-r300-p3-release-beverages.cjs'"),'regressão P3 registrada no PRE-APK');
console.log(`R300 P3 BEBIDAS: ${checks} contratos e cenários reais aprovados; sem rede, WhatsApp ou Firestore`);
