#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require(require.resolve('typescript',{paths:[process.env.DFL_R202_PROJECT_ROOT || process.cwd()]}));
let n=0;
const ok=(x,label)=>{assert.ok(x,`R202 ${label}`);n++;console.log('OK R202:',label)};
const read=(p)=>fs.readFileSync(p,'utf8');
const files=['lib/operation/delivery-import-identity.ts','lib/operation/legacy-import-audit.ts','components/diagnostics/LegacyImportAuditCard.tsx','app/mais/diagnostico/page.tsx'];
for(const p of files){const src=read(p),ast=ts.createSourceFile(p,src,ts.ScriptTarget.Latest,true,p.endsWith('tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);ok(!ast.parseDiagnostics.length,'sintaxe '+p)}
const tsload=(file,mocks={})=>{
 const js=ts.transpileModule(read(file),{fileName:file,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const module={exports:{}};
 const sandbox={exports:module.exports,module,require:(key)=>{if(Object.prototype.hasOwnProperty.call(mocks,key))return mocks[key];throw Error('Import inesperado: '+key)},Date,Intl,Math,Number,String,Set,Map,Array,Boolean,Error};
 vm.runInNewContext(js,sandbox,{filename:file});return module.exports;
};
const identity=tsload('lib/operation/delivery-import-identity.ts');
const audit=tsload('lib/operation/legacy-import-audit.ts',{'@/lib/operation/delivery-import-identity':identity});
const dt='2026-10-30T13:00:00.000Z';
const other='2026-10-31T13:00:00.000Z';
const base=(id,origin,order_id,ifood_id='',created_at=dt)=>({id,origin,order_id,ifood_id,created_at});
const old99=base('legacy-99','food99','123456');
const new99={...old99,id:identity.deliveryImportDocumentId(old99)};
const oldI=base('legacy-ifood','ifood','X-ABC','123456789');
const newI={...oldI,id:identity.deliveryImportDocumentId(oldI)};
const input=[old99,new99,oldI,newI,base('later-99','food99','123456','',other),base('different-channel','ifood','123456','987654321')];
const snapshot=JSON.stringify(input);
const result=audit.auditLegacyImports(input);
ok(result.total===6,'conta somente pedidos das plataformas');
ok(result.canonical===2 && result.legacy===4,'distingue R201 dos legados');
ok(result.strongGroups===2,'99Food do mesmo dia e iFood com ID forte detectados');
ok(result.reviewGroups===0,'o mesmo par não é contado de novo como suspeita');
ok(result.affectedDocuments===4,'conta documentos distintos envolvidos');
ok(!result.groups.some(g=>g.documentIds.includes('later-99')),'99Food de outro dia não é duplicata');
ok(!result.groups.some(g=>g.documentIds.includes('different-channel')),'números de canais diferentes não colidem');
ok(JSON.stringify(input)===snapshot,'auditoria não altera os registros originais');
const possible=audit.auditLegacyImports([base('a','ifood','AB2'),base('b','ifood','AB2')]);
ok(possible.strongGroups===0 && possible.reviewGroups===1,'número iFood sem ID forte fica apenas em revisão');
const incomplete=audit.auditLegacyImports([base('i','food99','1122'),base('j','ifood','','')]);
ok(incomplete.unidentified===2,'identidades incompletas reconhecidas sem bloqueio falso');
const site=audit.auditLegacyImports([ {...old99,source_system:'dfl_site'},base('loja','loja','123456') ]);
ok(site.total===0 && !site.groups.length,'Site e loja fora do escopo');
const invalid=audit.auditLegacyImports([base('bad1','food99','123456','','invalid'),base('bad2','food99','123456','','invalid')]);
ok(invalid.strongGroups===0 && invalid.unidentified===2,'datas ruins nunca viram colisão fabricada');
const report=audit.legacyAuditText(result);
ok(report.includes('legacy-99') && report.includes('Colisões fortes: 2'),'relatório rastreável pelos IDs internos');
ok(!/(Cliente:|WhatsApp:|Endereço:)/.test(report),'relatório não inclui identidade de clientes');
const component=read('components/diagnostics/LegacyImportAuditCard.tsx');
ok(!/\b(?:onSnapshot|runTransaction|getDocs|setDoc|deleteDoc|writeBatch)\s*\(/.test(component),'painel sem leituras ou gravações remotas');
ok(component.includes('useMemo(()=>auditLegacyImports(deliveries),[deliveries])'),'projeção memoizada por versão das entregas');
ok(component.includes('Copiar relatório') && component.includes('role="switch"'),'filtros e exportação funcional no painel');
const page=read('app/mais/diagnostico/page.tsx'),pre=read('scripts/pre-apk.cjs');
ok(page.includes('<LegacyImportAuditCard />')&&page.includes('DIAGNOSTICS_ADMIN_EMAIL'),'radar permanece na página administrativa');
ok(pre.includes("'scripts/test-r202-legacy-import-audit.cjs'"),'novo teste integrado ao pre-APK');
console.log(`R202: ${n} contratos de integridade e UX OK`);
