const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const read = (f) => fs.readFileSync(f, 'utf8');
const source = read('lib/ifood-confirmation-authority.ts');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }, reportDiagnostics: true });
assert.equal(compiled.diagnostics?.length || 0, 0, 'utilitário possui sintaxe válida');
const mod = new Module('ifood-authority', module);
mod.filename = process.cwd() + '/lib/ifood-confirmation-authority.ts';
mod.paths = module.paths;
mod._compile(compiled.outputText, mod.filename);
const { reconcileIfoodConfirmation } = mod.exports;
const incoming = { id:'ifood-route-d1', delivery_id:'d1', status:'pending', confirmation_code:'1234', note:'Rota encerrada', created_at:'2026-10-17T10:00:00Z', updated_at:'2026-10-17T10:00:00Z' };
const resolved = { ...incoming, confirmation_code:'5678', note:'Confirmado no portal', status:'resolved', resolved_at:'2026-10-17T11:00:00Z' };
assert.deepEqual(reconcileIfoodConfirmation(resolved, incoming), resolved, 'confirmação resolvida é imutável na geração automática');
assert.deepEqual(reconcileIfoodConfirmation(undefined, incoming), incoming, 'novo registro é criado');
assert.equal(reconcileIfoodConfirmation({ ...incoming, customer_name:'Ana' }, { ...incoming, customer_name:'Carolina' }).customer_name, 'Carolina');
const store = read('store/useAppStore.ts');
const close = store.slice(store.indexOf('      closeRoute: async'), store.indexOf('      reopenRoute: async'));
const reopen = store.slice(store.indexOf('      reopenRoute: async'), store.indexOf('      reorderDelivery: async'));
const pending = store.slice(store.indexOf('      addIfoodPendingConfirmations: async'), store.indexOf('      updateIfoodPendingConfirmation: async'));
const settle = store.slice(store.indexOf('      updateOperationalExpense: async'), store.indexOf('      addIfoodPendingConfirmations: async'));
assert(close.includes("where('route_id', '==', routeId)"), 'confere paradas remotas na ação de fechamento');
assert(close.includes('const remoteDeliveries = await Promise.all('), 'lê estado real das entregas');
assert(close.includes('remote.completed !== true'), 'impede fechar entregas não concluídas no servidor');
assert(close.indexOf('await runTransaction(') < close.indexOf("status: 'fechada', end_time: finalEndTime"), 'UI só confirma depois da transação');
assert(reopen.includes('transaction.get(ref)') && reopen.includes("saved.status !== 'fechada'"), 'reabertura exige status real fechado');
assert(pending.includes('reconcileIfoodConfirmation') && pending.includes('snapshots[index].exists()'), 'fila consulta documento existente antes de salvar');
assert(pending.includes("current.data().status === 'resolved'"), 'não reescreve documento já resolvido');
assert(settle.includes('transaction.delete(ref)') && (settle.match(/isClosedSettlement\(remote\)/g)||[]).length >= 2, 'edição e exclusão verificam acerto remoto');
const confirmationUI = read('app/confirmacoes/page.tsx');
assert(confirmationUI.includes('await Haptics.impact({ style });') && confirmationUI.includes('Feedback tátil não pode impedir'), 'haptics não bloqueiam confirmação');
const updater = store.slice(store.indexOf('      updateIfoodPendingConfirmation: async'), store.indexOf('      deleteIfoodPendingConfirmation: async'));
assert(updater.includes('deleteField()'), 'reabertura manual limpa resolved_at no servidor');
console.log('V100.6: fila iFood, fechamento/reabertura remotos, acerto e haptics — CONTRATOS OK');
