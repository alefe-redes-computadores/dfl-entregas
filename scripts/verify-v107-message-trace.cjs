const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const ts=require('typescript');
const read=p=>fs.readFileSync(p,'utf8');
const source=read('lib/integration/messageTrace.ts');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const sandbox={exports:{},require,Set};
vm.runInNewContext(js,sandbox,{timeout:1000});
const traceSummary=sandbox.exports.traceSummary;
const sample=(eventType,status)=>({eventId:'sample',eventType,status,attempts:1,occurredAt:null,processedAt:null,lastError:null});
const compare=(events,completed,verdict)=>assert.equal(traceSummary(events,completed).verdict,verdict);
compare([sample('delivery.completed','sent')],true,'site_accepted');
compare([sample('delivery.completed','failed')],true,'relay_failed');
compare([sample('delivery.completed','dead_letter')],true,'relay_failed');
compare([sample('delivery.completed','pending')],true,'relay_pending');
compare([],true,'no_terminal_event');
compare([],false,'no_event');
compare([sample('delivery.out_for_delivery','sent')],false,'site_accepted');
compare([sample('route.started','sent')],false,'no_event');
compare([sample('delivery.completed','sent'),sample('delivery.next_stop','failed')],true,'relay_failed');
assert.equal(traceSummary([sample('delivery.completed','sent')],true).whatsapp,'not_verified');
const route=read('app/api/integration/diagnostic/message-trace/route.ts');
const page=read('components/diagnostics/MessageTraceCard.tsx');
const diag=read('app/mais/diagnostico/page.tsx');
assert.match(route,/adminAuth\.verifyIdToken/);
assert.match(route,/configured\.includes\(email\)/);
assert.match(route,/\.where\('entity_id', '==', doc\.id\)\.limit\(MAX_EVENTS\)/);
assert.match(route,/\.where\('external_order_id', '==', id\)\.limit\(2\)/);
assert.match(route,/whatsappVerified: false/);
assert.match(route,/readOnly: true/);
assert.match(route,/export async function OPTIONS/);
assert.match(route,/NATIVE_ORIGINS.has/);
assert.match(route,/function safeError/);
assert.doesNotMatch(route,/lastError: asText\(event.last_error\)/);
assert.doesNotMatch(route,/\b(?:onSnapshot|\.set\(|\.update\(|\.delete\(|runTransaction\(|collection\('integration_notification_intents'\))/);
assert.doesNotMatch(page,/setInterval\(/);
assert.match(page,/getIdToken\(\)/);
assert.match(page,/AbortController/);
assert.match(diag,/<MessageTraceCard \/>/);
assert.match(diag,/WhatsApp não verificado/);
for(const file of ['app/api/integration/diagnostic/message-trace/route.ts','components/diagnostics/MessageTraceCard.tsx','app/mais/diagnostico/page.tsx']){
  const fileSource=read(file);
  const result=ts.transpileModule(fileSource,{fileName:file,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.Preserve,target:ts.ScriptTarget.ES2020}});
  const errors=(result.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error);
  assert.equal(errors.length,0,`${file}: ${errors.map(e=>ts.flattenDiagnosticMessageText(e.messageText,' ')).join(' | ')}`);
}
