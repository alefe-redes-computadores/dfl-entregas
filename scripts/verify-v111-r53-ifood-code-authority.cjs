#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
let checks = 0;
const ok = (v, label) => { assert.ok(v, `R53: ${label}`); checks++; };
const source = (file) => {
  const text = fs.readFileSync(file, 'utf8');
  const tree = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  ok(tree.parseDiagnostics.length === 0, `syntax ${file}`);
  return text;
};
const store = source('store/useAppStore.ts');
const wa = source('lib/whatsapp.ts');
const helper = source('lib/operation/ifoodOrderCode.ts');
const legacy = source('scripts/verify-v25-2-balcao-pos-rota-ifood.cjs');
const pre = source('scripts/pre-apk.cjs');
const close = store.slice(store.indexOf('      closeRoute: async'), store.indexOf('      reopenRoute: async'));
ok(close.includes('orderConfirmationCode(delivery.confirmation_code)'), 'post-route code belongs to delivery');
ok(!close.includes('customer?.last_confirmation_code'), 'post-route cannot reuse customer memory');
ok(close.includes("delivery.origin === 'ifood' && !isCancelledSiteDelivery(delivery)"), 'cancelled orders excluded');
ok(close.includes('id: `ifood-route-${delivery.id}`'), 'idempotent queue ID retained');
ok(close.includes("status: 'pending'"), 'external queue still pending');
ok(close.includes('await current.addIfoodPendingConfirmations(confirmationItems)'), 'external queue still persisted');
ok(close.includes('transaction.get(routeRef)'), 'remote authority retained');
ok(wa.includes('const currentCode = orderConfirmationCode(delivery.confirmation_code)'), 'individual WhatsApp uses delivery code');
ok(wa.includes('orderConfirmationCode(item.confirmation_code)'), 'grouped WhatsApp uses item code');
ok(wa.includes('orderConfirmationCode(candidate.confirmation_code)'), 'checklist uses item code');
ok(!wa.includes('candidateCustomer?.last_confirmation_code') && !wa.includes('customer?.last_confirmation_code'), 'WhatsApp never fills from customer memory');
ok(wa.includes('const missingIfoodCode = codes.some((code) => !code)'), 'group warns even with another valid code');
ok(wa.includes('else if (missingIfoodCode)'), 'mixed group prompts for missing code');
ok(wa.includes('const deliveriesByStop = new Map<string, Delivery[]>()'), 'one pass stop index');
ok(wa.includes('const groupedDeliveries = deliveriesByStop.get(groupKey) || []'), 'checklist uses index');
ok(!wa.includes('const groupedDeliveries = deliveries.filter('), 'quadratic grouping removed');
ok(store.includes('const freeByKey = new Map(freeGroups.map'), 'route organizer indexed by stop');
ok(!store.includes('freeGroups.find((group) => group.key === deliveryStopKey('), 'route organizer quadratic find removed');
ok(helper.includes('digits.length === 4 ? digits :'), 'codes are exactly four digits, no truncation');
ok(legacy.includes('fila pós-rota usa código do pedido'), 'legacy test now guards provenance');
const suites = [...pre.matchAll(/^  '(scripts\/[^']+\.cjs)'/gm)].map(m => m[1]);
ok(suites.length >= 188, `at least 188 PRE-APK suites, found ${suites.length}`);
ok(new Set(suites).size === suites.length, 'no duplicate tests');
for (const path of suites) ok(fs.existsSync(path), `suite exists ${path}`);
for (const newTest of ['scripts/verify-v111-r53-ifood-code-authority.cjs', 'scripts/test-v111-r53-ifood-code-authority.cjs']) ok(suites.includes(newTest), `R53 suite registered ${newTest}`);
ok(fs.readFileSync('security/firestore.v111-r23-owner-only.rules','utf8').includes('if superadmin();'),'owner-only Firestore Rules preserved');
console.log(`R53 AUTORIDADE IFOOD: ${checks} contratos aprovados; ${suites.length} suítes registradas`);
