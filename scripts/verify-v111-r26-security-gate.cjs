'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const rules=read('security/firestore.v111-r26-candidate.rules');
const wf=read('.github/workflows/firestore-r26-homologation.yml');
const tests=read('scripts/test-v111-r26-firestore-emulator.cjs');
const cfg=JSON.parse(read('firebase.r26-emulator.json'));
const pre=read('scripts/pre-apk.cjs');
const must=(v,description)=>{assert.ok(v,description);console.log('R26 OK:',description);};
must(/request\.auth\.uid\s*==\s*'zIfbMxD1SQNvtlX9y6YUsEz2TXC3'/.test(rules),'UID owner fixo');
must(!/allow\s+(?:read|write|create|update|delete|list|get)[^;]*if\s+(?:true|request\.auth\s*!=\s*null)\s*;/.test(rules),'nenhuma regra aberta');
must(rules.includes('allow read, write: if owner();'),'coringa exclusiva ao owner');
must(rules.includes("get(accountRef(uid)).data.status == 'active'"),'status ativo exigido');
must(rules.includes('request.auth.uid == uid'),'isolamento pelo UID');
must(rules.includes('request.query.limit <= 40'),'queries limitadas');
must(rules.includes('allow create, update, delete: if false;'),'funcionario sem mutacoes diretas');
must(rules.includes("get(accountRef(uid)).data.role != 'motoboy'") && rules.includes("get(accountRef(uid)).data.role != 'compras'"),'perfil restringe acessos');
must(cfg.firestore.rules==='security/firestore.v111-r26-candidate.rules','config usa candidato R26');
must(cfg.emulators.firestore.host==='127.0.0.1'&&cfg.emulators.firestore.port===8087,'loopback exclusivo do emulador');
must(/workflow_dispatch/.test(wf)&&!/\bon:\s*\[?push|pull_request/.test(wf),'workflow exclusivamente manual');
must(!/firebase\s+deploy|firebase-admin|firebase\.googleapis\.com/.test(wf),'sem deploy e sem Admin SDK no workflow');
must(wf.includes('--project demo-dfl-entregas-r26'),'projeto demo no workflow');
must(tests.includes("assert.equal(process.env.FIRESTORE_EMULATOR_HOST,HOST")&&tests.includes("assert.equal(process.env.GCLOUD_PROJECT,PROJECT"),'teste recusa host ou projeto real');
must(tests.includes('assertSucceeds')&&tests.includes('assertFails'),'testes positivos e negativos');
must(tests.includes('revogacao imediata com o mesmo token')&&tests.includes('motoboy nao escreve projecoes'),'revogacao e escrita indevida cobertos');
const v24wf=read('.github/workflows/firestore-r24-homologation.yml');
const emulatorDependency='npm install --no-save --package-lock=false firebase-tools@14 @firebase/rules-unit-testing@3.0.4';
must(wf.includes(emulatorDependency),'R26: versao do emulador compativel com Firebase 10');
must(v24wf.includes(emulatorDependency),'R24: versao do emulador compativel com Firebase 10');
must(!/--legacy-peer-deps|--force/.test(wf+v24wf),'instalacao sem forcar dependencias incompativeis');
must(pre.includes("'scripts/verify-v111-r26-security-gate.cjs'"),'gate R26 registrado no PRE-APK');
console.log('R26 GATE ESTATICO: OK. Teste REAL do emulador requer Action manual apos publicacao.');
