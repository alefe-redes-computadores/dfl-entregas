'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const file = 'lib/operation/snapshot-sync-safety.ts';
const src = fs.readFileSync(file, 'utf8');
const parsed=ts.createSourceFile(file,src,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
assert.equal(parsed.parseDiagnostics.length,0,'TypeScript parse');
const compiled=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod=new Module(file,module); mod.filename=file; mod.paths=module.paths; mod._compile(compiled,file);
const {captureOperationalBaseline,preserveInFlightLocalEdits}=mod.exports;
const sig=x=>x.value;
const base=[{id:'changed',value:'old'},{id:'deleted',value:'old'},{id:'stable',value:'old'}];
const baseline=captureOperationalBaseline(base,sig);
const cloud=[{id:'changed',value:'remote'},{id:'deleted',value:'remote'},{id:'stable',value:'remote'},{id:'remote-only',value:'remote'}];
const local=[{id:'changed',value:'local-new'},{id:'stable',value:'old'},{id:'created',value:'new'}];
const result=preserveInFlightLocalEdits(cloud,local,baseline,sig);
assert.deepEqual(result.map(x=>x.id),['changed','stable','remote-only','created']);
assert.equal(result[0].value,'local-new');
assert.equal(result[1].value,'remote');
assert.equal(result[3].value,'new');
assert.deepEqual(preserveInFlightLocalEdits([],local,baseline,sig).map(x=>x.id),['created']);
assert.deepEqual(preserveInFlightLocalEdits([{id:'stable',value:'remote'}],[],baseline,sig).map(x=>x.id),[]);
assert.deepEqual(preserveInFlightLocalEdits([{id:'remote-only',value:'cloud'}],[{id:'remote-only',value:'local'}],new Map(),sig).map(x=>x.id),['remote-only']);
console.log('R138: 7 contratos de merge em voo OK');
