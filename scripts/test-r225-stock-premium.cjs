#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const ts=require('typescript');
const vm=require('node:vm');
let checks=0;
function ok(condition,label){assert.ok(condition,'R225: '+label);checks++;console.log('OK R225:',label);}
const read=p=>fs.readFileSync(p,'utf8');
const src=read('lib/stock-movement-shortcuts.ts');
const tree=ts.createSourceFile('lib/stock-movement-shortcuts.ts',src,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
ok(!tree.parseDiagnostics.length,'Helper TypeScript sintaticamente válido');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const sandboxModule={exports:{}};
vm.runInNewContext(js,{module:sandboxModule,exports:sandboxModule.exports,Number,Math,Intl}, {filename:'stock-movement-shortcuts.js'});
const {fullStockQuantityInput,canShortcutAllStock,movementStockSignal}=sandboxModule.exports;
ok(fullStockQuantityInput(3.4)==='3,4','Tudo: 3,4 kg sem conversão inventada');
ok(fullStockQuantityInput(7)==='7','Tudo: sete unidades');
ok(fullStockQuantityInput(.5833)==='0,5833','Tudo: frações de embalagem preservadas');
ok(fullStockQuantityInput(1234.1)==='1234,1','Tudo: input sem separador de milhar');
ok(fullStockQuantityInput(0)===''&&fullStockQuantityInput(-1)===''&&fullStockQuantityInput(NaN)==='','Tudo: saldo indisponível nunca vira baixa');
ok(canShortcutAllStock('saida','moved',3.4),'Tudo habilitado em saída');
ok(canShortcutAllStock('perda','moved',7),'Tudo habilitado em perda');
ok(!canShortcutAllStock('saida','remaining',7),'Tudo não confunde quanto sobrou');
ok(!canShortcutAllStock('contagem','moved',7),'Tudo não confunde contagem');
ok(!canShortcutAllStock('entrada','moved',7),'Tudo não confunde entrada');
ok(!canShortcutAllStock('saida','moved',0),'Tudo indisponível com saldo zerado');
ok(movementStockSignal('saida',0,5)==='O estoque ficará zerado','sinal antecipado de ruptura');
ok(movementStockSignal('saida',3,5)==='Saldo projetado abaixo do mínimo','aviso de mínimo');
ok(movementStockSignal('saida',5,5)===null,'saldo no mínimo não inventa ruptura');
ok(movementStockSignal('entrada',8,5)===null,'entrada normal sem aviso falso');
const movement=read('app/estoque/movimentar/page.tsx');
ok(movement.includes("setPresentationId('base'); setQuantity(fullStockQuantityInput(product.current_quantity))"),'Tudo sempre seleciona unidade base');
ok(movement.includes("canShortcutAllStock(type, mode, product.current_quantity)"),'Tudo condicionado a saída/perda');
ok(movement.includes('aria-label={`Informar todo o saldo disponível:'),'Tudo acessível');
ok(!movement.includes('autoFocus\n            inputMode="decimal"'),'teclado não sequestra abertura da movimentação');
ok(movement.includes('stockMovementBaseQuantity(typed, conversion, product.current_quantity'),'conversão antiga preservada');
ok(movement.includes('quantity === fullStockQuantityInput(product.current_quantity)'),'saldo integral com quatro casas não é arredondado no blur');
ok(movement.includes('stockExitExceeds(rawAmount, product.current_quantity'),'proteção de estoque insuficiente preservada');
ok(movement.includes('expected_balance: product.current_quantity'),'conferência de saldo antes da gravação preservada');
ok(movement.includes('savingRef.current = true'),'trava contra toques repetidos preservada');
ok(movement.includes('data-dfl-stock-advanced'),'campos secundários recolhidos, sem exclusão');
ok(movement.includes('TeamMemberPicker')&&movement.includes('setReason('),'responsável e motivo mantidos');
ok(movement.includes('aria-label="Equivalencia por embalagem"')&&movement.includes('summary'),'equivalência preservada em detalhes');
ok(!movement.includes('await notifyStockThresholdChanges(changes, useAppStore.getState().storeSettings.notificationPreferences)'),'notificação pós-gravação não bloqueia navegação');
ok((movement.match(/void notifyStockThresholdChanges\(changes/g)||[]).length===2,'aviso de conferência segue em ambos caminhos');
const purchase=read('app/estoque/compras/page.tsx');
ok(purchase.includes('Por que esta sugestão?')&&purchase.includes('operationTiming.minimum')&&purchase.includes('operationTiming.zero'),'previsão preservada sob detalhe');
ok(purchase.includes('buildStockRecommendations')&&purchase.includes('guardedStockRecommendation'),'motor inteligente de compras preservado');
ok(purchase.includes('validateStockPurchaseQuantity('),'unidades de compra continuam validadas');
const supply=read('components/stock-supplies/StockSupplyForm.tsx');
ok(supply.includes('draftStorageFailed')&&supply.includes('stockSupplyDraftKey'),'rascunhos de compras protegidos');
ok(supply.includes('StockProductPicker')&&supply.includes('StockSupplierPicker'),'formulário preserva vínculos');
const store=read('store/useAppStore.ts');
ok(store.includes('const [productSnap, priorMovement] = await Promise.all(['),'estoque ainda exige transação remota com idempotência');
ok(store.includes('transaction.update(productRef, sanitizeForFirebase(plan.changed))'),'estoque atualizado na transação');
ok(store.includes('transaction.set(movementRef, sanitizeForFirebase(plan.record))'),'movimento e saldo seguem atômicos');
ok(store.includes('recordActionLatency(\'stock_movement\'') && store.includes('recordActionLatency(\'stock_supply\''),'telemetria local após transações');
ok(store.includes('stockWriteConnectionError(error)'),'erros de rede continuam explícitos');
const latency=read('lib/operation/action-latency.ts');
ok(latency.includes("stock_movement: 'Movimentação de estoque'")&&latency.includes("stock_supply: 'Compra de estoque'"),'diagnóstico inclui estoque e compras');
ok(latency.includes('const MAX_SAMPLES = 60')&&latency.includes('sanitizeActionLatencies('),'diagnóstico limitado e saneado');
const notification=read('lib/native/notifications.ts');
ok(notification.includes('stockProductsInFlight.add(key)')&&notification.includes('stockProductsInFlight.delete(key)'),'notificações ainda têm trava e cleanup');
ok(notification.includes('persistentLastSent')&&notification.includes('preferenceEnabled(preferences'),'notificações respeitam preferências e cooldown');
const pre=read('scripts/pre-apk.cjs');
ok(pre.includes("'scripts/test-r225-stock-premium.cjs'")&&pre.includes("'scripts/test-r224-final-closeout.cjs'"),'R225 adicionada sem suprimir R224');
for(const file of ['app/estoque/movimentar/page.tsx','app/estoque/compras/page.tsx','components/stock-supplies/StockSupplyForm.tsx','store/useAppStore.ts','lib/operation/action-latency.ts']){
 const jsx=file.endsWith('.tsx');const t=ts.createSourceFile(file,read(file),ts.ScriptTarget.Latest,true,jsx?ts.ScriptKind.TSX:ts.ScriptKind.TS);
 ok(!t.parseDiagnostics.length,'TypeScript parse '+file+' '+t.parseDiagnostics.map(z=>z.messageText).join('; '));
}
console.log(`R225 PREMIUM ESTOQUE: ${checks} verificações aprovadas, sem escrever no Firebase.`);
