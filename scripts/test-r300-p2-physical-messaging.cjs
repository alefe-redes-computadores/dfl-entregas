const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const file='lib/integration/manualNextStopPolicy.ts';
const source=fs.readFileSync(file,'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020},reportDiagnostics:true});
assert.equal(compiled.diagnostics.length,0,'TypeScript parse');
const context={exports:{},require(name){if(name==='@/lib/route-stops')return{deliveryStopKey:d=>`address:${d.route_id}:${String(d.address_string).toLowerCase().trim()}`};throw Error(`unexpected import ${name}`);}};
vm.runInNewContext(compiled.outputText,context,{filename:file});
const plan=context.exports.planManualNextStopTransition;
const t=Date.parse('2026-11-08T22:00:00.000Z');
const route={id:'route-real-12345678',status:'aberta',started_at:new Date(t-3600000).toISOString()};
const stops=['A','B','B','C','D','E','F'].map((s,i)=>({id:`dfl-manual-test-${i}-123456789`,route_id:route.id,origin:'loja',source_system:'dfl_entregas',fulfillment_mode:'delivery',address_string:s,order_index:i===2?1:i>2?i-1:i,completed:false,manual_messaging_opt_in_v1:true,notify_whatsapp:true,phone:'34999999999'}));
assert.equal(plan({route,deliveries:stops,now:t}),null,'não pode notificar antes da primeira conclusão física');
stops[0].completed=true;stops[0].completed_at=new Date(t-1000).toISOString();
const p1=plan({route,deliveries:stops,now:t});
assert.equal(p1.plannedStop,2,'parada 2 após conclusão da 1');
assert.equal(p1.totalStops,6,'7 pedidos / 6 paradas físicas');
assert.equal(p1.nextDeliveries.length,2,'dois pedidos na mesma parada');
stops[1].completed=true;stops[1].completed_at=new Date(t-700).toISOString();
const partial=plan({route,deliveries:stops,now:t});
assert.equal(partial.plannedStop,2,'baixa isolada no grupo não muda próximo grupo');
stops[2].completed=true;stops[2].completed_at=new Date(t-500).toISOString();
const p2=plan({route,deliveries:stops,now:t});
assert.equal(p2.plannedStop,3,'apenas baixa final da segunda parada avança');
assert.equal(p2.nextDeliveries.length,1,'apenas grupo 3 é o próximo');
stops[3].order_updated_at=new Date(t+1000).toISOString();
assert.equal(plan({route,deliveries:stops,now:t+1500}),null,'reordenação posterior suprime transição obsoleta');
delete stops[3].order_updated_at;
assert.equal(plan({route:{...route,status:'fechada'},deliveries:stops,now:t}),null,'rota fechada');
assert.equal(plan({route:{...route,started_at:''},deliveries:stops,now:t}),null,'rota não iniciada');
assert.equal(plan({route,deliveries:stops,now:t+9*60_000}),null,'backlog antigo não gera aviso');
const bridge=fs.readFileSync('lib/integration/server/manualNextStop.ts','utf8');
const kick=fs.readFileSync('app/api/integration/route-kick/route.ts','utf8');
const siteContract='manual-msg-v2__delivery.next_stop__';
assert(bridge.includes(siteContract)&&bridge.includes('transitionKey')&&bridge.includes(".create({event_id:id"),'identidade persistente por transição');
assert(bridge.includes("DFL_MANUAL_NEXT_STOP_ENABLED === 'true'")&&bridge.includes("DFL_MANUAL_NEXT_STOP_KILL_SWITCH === 'false'"),'duplo gate fail closed');
assert(bridge.includes('uncertain')&&bridge.includes('timeout_or_network_unknown'),'timeout não vira reenfileiramento silencioso');
assert(kick.includes("reason === 'delivery_completed'")&&kick.includes('notifyManualNextStop(routeId)'),'gatilho somente após baixa persistida');
assert(!bridge.includes('manual_order_items')&&!bridge.includes('sendText/')&&!bridge.includes('ETA'),'não há template nem provedor direto no Entregas');
console.log('R300 P2: transições físicas, multi-pedido, reordenação, tempo, autorização OFF e idempotência em contrato OK. Sem rede.');
